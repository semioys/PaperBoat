#!/usr/bin/env python3
"""Generates src/port/switch/sound_haptics_table.inc.

Classifies the game's sound effect ids (SOUND_* in include/enums.h) into HD
Rumble categories by name, so every physical event that makes a sound - block
bumps, hammer strikes, explosions, doors, pickups - also gets a matching
vibration. Looping sounds, footsteps, voices and menu sounds are skipped.

The table uses the enum names; the compiler resolves the values.
Run from the repository root:  python tools/switch/gen_sound_haptics.py
"""
import re
import sys

ENUMS = "include/enums.h"
OUTPUT = "src/port/switch/sound_haptics_table.inc"

# Never vibrate for these (continuous, too frequent, or not physical).
EXCLUDE = re.compile(
    r"^SOUND_(LOOP_|LRAW_|MENU_|MSG_|TYPE_|OUT_|ID_|SPACE_|PARAM|SEQ_.*(BOUNCE)|STEP|.*_STEP|"
    r".*VOICE|.*UNUSED|.*FUSE|.*SWING|.*SWIPE|.*WINDUP|.*SNORE|.*TALK|.*BOUNCE|.*WHOOSH|.*FLIP_PAGE|"
    r".*_LOOP$|HIT_SILENT$)"
)

# Enemies healing or powering up should not feel like Mario getting something.
ENEMY = re.compile(r"BOWSER|KPA_|MAGIKOOPA|LAVA_BUD|LAVA_PIRANHA|KAMMY")

# First match wins. Category names match PB_SFX_* in sound_haptics.c.
RULES = [
    ("CELEBRATE", r"JINGLE_GOT|POWER_UP|SAVE_CONFIRM|GET_STAR_POWER|LEVEL_UP"),
    ("HEAL", r"HEART_PICKUP|FLOWER_PICKUP|RECOVER|HEART_BLOCK|HEAL"),
    ("PICKUP", r"COIN_PICKUP|STAR_POINT_PICKUP|STAR_PIECE|_PICKUP"),
    ("EXPLOSION", r"EXPLO|BLAST|BOMB|SHOCKWAVE|POW_BLOCK"),
    ("SHOCK", r"SHOCK|LIGHTNING|THUNDER"),
    ("HAMMER", r"HAMMER_STRIKE|SMASH_HAMER|SPIN_SMASH|HAMMER_QUAKE|SMACK_TREE|D_DOWN_HIT"),
    ("BREAK", r"SHATTER|BREAK|CRASH|DESTROY"),
    ("PLAYER_HURT", r"HIT_PLAYER|PLAYER_COLLAPSE|DAMAGE_STARS"),
    ("BUMP", r"HIT_BLOCK|WOODEN_BLOCK|ACTIVATE_SWITCH|FLOOR_SWITCH|PUSH_BLOCK|SPAWN_BLOCK|HEADBONK|SUMMON_BLOCK"),
    ("THUD", r"THUD|COLLAPSE|SLAM|IMPACT|QUAKE|RUMBLE|LANDING|_LAND$|POUND|HEAVY"),
    ("JUMP", r"SPIN_JUMP|LAND_SPIN_JUMP|LAND_TORANDO_JUMP|TORNADO|SPRING"),
    ("DOOR", r"DOOR|CHEST|TRAPDOOR|ENTER_PIPE|GATE_(OPEN|CLOSE)"),
    ("HIT", r"^SOUND_HIT_|SMACK|STRIKE|_HIT(_|$)"),
]


def main():
    text = open(ENUMS, encoding="utf-8").read()
    # Only names inside the sound id enum (they all start with SOUND_ and have an initializer).
    names = []
    seen = set()
    for m in re.finditer(r"^\s+(SOUND_[A-Z0-9_]+)\s*=", text, re.MULTILINE):
        name = m.group(1)
        if name in seen:
            continue
        seen.add(name)
        names.append(name)

    rows = []
    counts = {}
    for name in names:
        if EXCLUDE.match(name):
            continue
        body = name[len("SOUND_"):]
        for category, pattern in RULES:
            if category in ("HEAL", "CELEBRATE") and ENEMY.search(body):
                continue
            if re.search(pattern, body) or re.search(pattern, name):
                rows.append((name, category))
                counts[category] = counts.get(category, 0) + 1
                break

    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as out:
        out.write("// Generated by tools/switch/gen_sound_haptics.py - do not edit.\n")
        out.write("// { sound id, PB_SFX_* category }\n")
        for name, category in rows:
            out.write(f"    {{ {name}, PB_SFX_{category} }},\n")
    print(f"{len(rows)} sounds mapped: " + ", ".join(f"{k}={v}" for k, v in sorted(counts.items())))


if __name__ == "__main__":
    sys.exit(main())
